package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"github.com/samber/lo"
)

var (
	domainTitles = map[string]string{
		"general": "General",
		"build":   "Build",
		"deploy":  "Deploy",
		"cleanup": "Cleanup",
		"go-api":  "Go API",
	}
	prNumberRegexp = regexp.MustCompile(`\(#(\d+)\)$`)
	sections       = []section{
		{match: func(e *entry) bool { return isBreaking(e) }, title: "Breaking changes"},
		{match: func(e *entry) bool { return !isBreaking(e) && e.Type == typeDeprecation }, title: "Deprecations"},
		{match: func(e *entry) bool { return !isBreaking(e) && e.Type == typeFeature }, title: "New features"},
		{match: func(e *entry) bool {
			return !isBreaking(e) && (e.Type == typeChange || e.Type == typeRemoval)
		}, title: "Other changes"},
		{match: func(e *entry) bool { return !isBreaking(e) && e.Type == typeFix }, title: "Fixes"},
	}
)

type section struct {
	match func(e *entry) bool
	title string
}

func render(cat *catalogue, dataDir string) error {
	refs := entryRefs(cat)

	for _, p := range cat.config.Products {
		entries := lo.Filter(sortedEntries(cat), func(e *entry, _ int) bool { return lo.Contains(e.Products, p.Name) })
		slices.SortStableFunc(entries, func(a, b *entry) int { return strings.Compare(a.Title, b.Title) })

		var b strings.Builder

		fmt.Fprintf(&b, "<!-- Generated by `task generate` from %s/ and %s/. Do not edit. -->\n\n",
			entriesDirName, ledgerDirName)
		fmt.Fprintf(&b, "# %s\n\n", p.Title)
		b.WriteString("Every user-visible change found in the commit ranges below. See [README.md](README.md) for how the catalogue is built and filtered.\n\n")
		b.WriteString("| Repository | Old | New |\n|---|---|---|\n")

		for _, r := range cat.config.Ranges {
			fmt.Fprintf(&b, "| [%s](%s) | %s | %s (`%s`) |\n", r.Name, r.URL,
				strings.Join(lo.Map(r.Old, func(o pin, _ int) string { return fmt.Sprintf("%s (`%s`)", o.Ref, short(o.Commit)) }), ", "),
				r.New.Ref, short(r.New.Commit))
		}

		b.WriteString("\n| Section | Entries |\n|---|---|\n")

		for _, s := range sections {
			fmt.Fprintf(&b, "| %s | %d |\n", s.title, len(lo.Filter(entries, func(e *entry, _ int) bool { return s.match(e) })))
		}

		for _, s := range sections {
			sectionEntries := lo.Filter(entries, func(e *entry, _ int) bool { return s.match(e) })
			if len(sectionEntries) == 0 {
				continue
			}

			fmt.Fprintf(&b, "\n## %s\n", s.title)

			for _, domain := range domains {
				domainEntries := lo.Filter(sectionEntries, func(e *entry, _ int) bool { return e.Domain == domain })
				if len(domainEntries) == 0 {
					continue
				}

				fmt.Fprintf(&b, "\n### %s\n", domainTitles[domain])

				for _, e := range domainEntries {
					renderEntry(&b, e, refs[e.ID])
				}
			}
		}

		path := filepath.Join(dataDir, p.Output)
		if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
			return fmt.Errorf("write %q: %w", path, err)
		}
	}

	return nil
}

// entryRefs links every entry to the pull requests of its ledger commits, or to the commits themselves
// when the subject names no pull request.
func entryRefs(cat *catalogue) map[string][]string {
	refs := map[string][]string{}

	for _, r := range cat.config.Ranges {
		for _, row := range cat.ledgers[r.Name] {
			link := fmt.Sprintf("[%s@%s](%s/commit/%s)", r.Name, short(row.Commit), r.URL, row.Commit)
			if m := prNumberRegexp.FindStringSubmatch(row.Subject); m != nil {
				link = fmt.Sprintf("[%s#%s](%s/pull/%s)", r.Name, m[1], r.URL, m[1])
			}

			for _, id := range row.Entries {
				if !lo.Contains(refs[id], link) {
					refs[id] = append(refs[id], link)
				}
			}
		}
	}

	return refs
}

func isBreaking(e *entry) bool {
	return e.Breaking != nil && *e.Breaking
}

func renderEntry(b *strings.Builder, e *entry, refs []string) {
	fmt.Fprintf(b, "\n#### %s\n\n", e.Title)
	fmt.Fprintf(b, "<a id=\"%s\"></a>`%s` · %s · %s · products: %s\n\n", e.ID, e.ID, e.Type,
		strings.Join(lo.Map(e.Areas, func(a string, _ int) string { return "`" + a + "`" }), " "),
		strings.Join(e.Products, ", "))
	b.WriteString(strings.TrimSpace(e.Description) + "\n")

	if strings.TrimSpace(e.Migration) != "" {
		fmt.Fprintf(b, "\n**Migration:** %s\n", strings.TrimSpace(e.Migration))
	}

	allRefs := append(slices.Clone(refs), lo.Map(e.Refs, func(ref string, _ int) string { return "<" + ref + ">" })...)
	if len(allRefs) > 0 {
		fmt.Fprintf(b, "\n**References:** %s\n", strings.Join(allRefs, ", "))
	}
}

func short(sha string) string {
	return sha[:min(len(sha), 9)]
}
